import { concat, utf8 } from '../formats/bytes.js';
import { SRGB_D50 } from './profile.js';
const word=(n:number)=>{const b=new Uint8Array(4);new DataView(b.buffer).setUint32(0,n);return b;};
const fixed=(n:number)=>word(Math.round(n*65536));
const xyz=(values:number[])=>concat([utf8('XYZ '),word(0),...values.map(fixed)]);
function text(value:string) {
  const payload=new Uint8Array(value.length*2),view=new DataView(payload.buffer);Array.from(value).forEach((c,i)=>view.setUint16(i*2,c.charCodeAt(0)));
  return concat([utf8('mluc'),word(0),word(1),word(12),utf8('enUS'),word(payload.length),word(28),payload]);
}
/** A generated ICC v4 sRGB matrix/TRC profile; no third-party binary asset. */
export function srgbProfile():Uint8Array {
  const curve=concat([utf8('para'),word(0),new Uint8Array([0,4,0,0]),...[2.4,1/1.055,.055/1.055,1/12.92,.04045,0,0].map(fixed)]);
  const tags=[['desc',text('sRGB')],['cprt',text('Public domain; generated by glass-ux-image')],['wtpt',xyz([.9642,1,.8249])],...['r','g','b'].map((c,i)=>[`${c}XYZ`,xyz([SRGB_D50[i]!,SRGB_D50[3+i]!,SRGB_D50[6+i]!])]),...['r','g','b'].map(c=>[`${c}TRC`,curve])] as [string,Uint8Array][];
  let offset=132+tags.length*12;const table:Uint8Array[]=[],payload:Uint8Array[]=[];
  for(const [name,data] of tags){table.push(concat([utf8(name),word(offset),word(data.length)]));const padded=new Uint8Array(Math.ceil(data.length/4)*4);padded.set(data);payload.push(padded);offset+=padded.length;}
  const header=new Uint8Array(128),v=new DataView(header.buffer);v.setUint32(0,offset);v.setUint32(8,0x04300000);header.set(utf8('mntrRGB XYZ '),12);v.setUint16(24,2026);v.setUint16(26,1);v.setUint16(28,1);header.set(utf8('acsp'),36);v.setUint32(64,1);header.set(xyz([.9642,1,.8249]).subarray(8),68);
  return concat([header,word(tags.length),...table,...payload]);
}
